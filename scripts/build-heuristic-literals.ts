/**
 * Generates lib/heuristic-literals.ts: the prefilter literals of each built-in detect pattern and the literal index
 * over them, so pages don't parse the pattern sources or build the index at load time. Run after changing DETECT_PATTERNS;
 * a unit test fails while the table is stale. See docs/heuristic-prefilter.md.
 */
import fs from 'fs';
import path from 'path';
import { DETECT_PATTERNS } from '../lib/heuristic-patterns';
import { literalIndexSource } from '../lib/heuristic-prefilter';
import { requiredLiterals } from './required-literals';

const OUT = path.join(__dirname, '../lib/heuristic-literals.ts');

const table: Record<string, string[]> = {};
for (const p of DETECT_PATTERNS) {
    const pattern = p instanceof RegExp ? p : p.pattern;
    table[pattern.toString()] = requiredLiterals(pattern);
}
const entries = Object.entries(table).map(([id, literals]) => `    ${JSON.stringify(id)}: ${JSON.stringify(literals)},`);
fs.writeFileSync(
    OUT,
    [
        '// Generated by `npm run build-heuristic-literals` from DETECT_PATTERNS. Do not edit.',
        '// The literals each pattern needs to match (see scripts/required-literals.ts and docs/heuristic-prefilter.md).',
        'export const DETECT_PATTERN_LITERALS: Record<string, string[]> = {',
        ...entries,
        '};',
        '',
        '// The literal index over them (see literalIndexSource in heuristic-prefilter.ts).',
        `export const DETECT_LITERAL_INDEX = ${JSON.stringify(literalIndexSource(Object.values(table).flat()))};`,
        '',
    ].join('\n'),
);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${entries.length} patterns)`);
